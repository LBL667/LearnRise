#!/usr/bin/env node
/**
 * sync-cast.mjs — regenerate the cast model from the promo manifest.
 *
 * Source of record:
 *   /home/sky/竞赛/华为ICT-evidence/learnrise-promo/promo_manifest.json
 *
 * Writes:
 *   src/content/cast.ts
 *   /home/sky/竞赛/华为ICT-evidence/learnrise-penpot/specs/cast.json
 *
 * Deterministic: no timestamps, no random ids, stable ordering. Running it
 * twice on an unchanged manifest must produce byte-identical files.
 *
 * Usage:
 *   node scripts/sync-cast.mjs [--manifest=<path>] [--penpot=<dir>] [--json]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(SCRIPT_DIR, '..');

const DEFAULTS = {
  manifest: '/home/sky/竞赛/华为ICT-evidence/learnrise-promo/promo_manifest.json',
  penpot: '/home/sky/竞赛/华为ICT-evidence/learnrise-penpot/specs',
};

const argv = process.argv.slice(2);
const valueOf = (name) => {
  const prefix = `--${name}=`;
  const hit = argv.find((argument) => argument.startsWith(prefix));
  return hit ? hit.slice(prefix.length) : undefined;
};

const manifestPath = path.resolve(
  valueOf('manifest') || process.env.PROMO_MANIFEST || DEFAULTS.manifest,
);
const penpotDir = path.resolve(
  valueOf('penpot') || process.env.PENPOT_SPECS_DIR || DEFAULTS.penpot,
);
const asJson = argv.includes('--json');

const fail = (message) => {
  process.stderr.write(`sync-cast: ${message}\n`);
  process.exit(1);
};

const readManifest = () => {
  let raw;
  try {
    raw = fs.readFileSync(manifestPath, 'utf8');
  } catch (error) {
    fail(`cannot read ${manifestPath}: ${error.message}`);
  }
  try {
    return JSON.parse(raw);
  } catch (error) {
    fail(`invalid JSON in ${manifestPath}: ${error.message}`);
  }
};

const asStudent = (entry, rank) => ({
  id: String(entry.id),
  name: String(entry.name),
  email: String(entry.email),
  points: Number(entry.points),
  cards: Number(entry.cards ?? 0),
  correct: Number(entry.correct ?? 0),
  rank,
});

const stableSort = (rows) =>
  rows.slice().sort((a, b) => {
    if (b.points !== a.points) return b.points - a.points;
    return a.name.localeCompare(b.name, 'zh-Hans-CN');
  });

const build = (manifest) => {
  const users = Array.isArray(manifest.users) ? manifest.users : [];
  const teachers = users
    .filter((user) => user.role === 'teacher')
    .map((user) => ({
      id: String(user.id),
      name: String(user.display_name),
      email: String(user.email),
    }));

  const rawStudents = Array.isArray(manifest.students)
    ? manifest.students
    : users
        .filter((user) => user.role === 'student')
        .map((user) => ({
          id: user.id,
          name: user.display_name,
          email: user.email,
          points: 0,
          cards: 0,
          correct: 0,
        }));

  const students = stableSort(rawStudents).map((entry, index) =>
    asStudent(entry, index + 1),
  );

  const competitions = Array.isArray(manifest.competitions)
    ? manifest.competitions
    : [];
  const mainId = manifest.main_competition?.id;
  const mainRow =
    competitions.find((competition) => competition.id === mainId) ||
    competitions.find((competition) => competition.is_main) ||
    competitions[0] ||
    {};

  const mainCompetition = {
    id: String(manifest.main_competition?.id ?? mainRow.id ?? ''),
    title: String(manifest.main_competition?.title ?? mainRow.title ?? ''),
    invite_code: String(
      manifest.main_competition?.invite_code ?? mainRow.invite_code ?? '',
    ),
    owner_email: String(mainRow.owner_email ?? ''),
  };

  const source = manifest.source
    ? {
        id: String(manifest.source.id),
        competition_id: String(manifest.source.competition_id),
        title: String(manifest.source.title),
        filename: String(manifest.source.filename),
        status: String(manifest.source.status),
      }
    : null;

  return {
    students,
    teachers,
    leaderboard: students,
    mainCompetition,
    inviteCode: mainCompetition.invite_code,
    source,
  };
};

const studentLiteral = (student) => `  {
    id: ${JSON.stringify(student.id)},
    name: ${JSON.stringify(student.name)},
    email: ${JSON.stringify(student.email)},
    points: ${student.points},
    cards: ${student.cards},
    correct: ${student.correct},
    rank: ${student.rank},
  },`;

const teacherLiteral = (teacher) => `  {
    id: ${JSON.stringify(teacher.id)},
    name: ${JSON.stringify(teacher.name)},
    email: ${JSON.stringify(teacher.email)},
  },`;

const renderTs = (cast, manifestRelative) => `// AUTO-GENERATED by \`npm run sync-cast\` from ${manifestRelative}.
// Do not hand-edit: change promo_manifest.json and re-run the generator.

export interface CastStudent {
  readonly id: string;
  readonly name: string;
  readonly email: string;
  readonly points: number;
  readonly cards: number;
  readonly correct: number;
  readonly rank: number;
}

export interface CastTeacher {
  readonly id: string;
  readonly name: string;
  readonly email: string;
}

export interface CastCompetition {
  readonly id: string;
  readonly title: string;
  readonly inviteCode: string;
  readonly ownerEmail: string;
}

export interface CastSource {
  readonly id: string;
  readonly competitionId: string;
  readonly title: string;
  readonly filename: string;
  readonly status: string;
}

/** Students sorted by points descending; rank is 1-based. */
export const STUDENTS: readonly CastStudent[] = [
${cast.students.map(studentLiteral).join('\n')}
];

/** Teachers are cast members but never enter the leaderboard. */
export const TEACHERS: readonly CastTeacher[] = [
${cast.teachers.map(teacherLiteral).join('\n')}
];

/** The leaderboard is students only. */
export const LEADERBOARD: readonly CastStudent[] = STUDENTS;

export const MAIN_COMPETITION: CastCompetition = {
  id: ${JSON.stringify(cast.mainCompetition.id)},
  title: ${JSON.stringify(cast.mainCompetition.title)},
  inviteCode: ${JSON.stringify(cast.mainCompetition.invite_code)},
  ownerEmail: ${JSON.stringify(cast.mainCompetition.owner_email)},
};

export const INVITE_CODE = ${JSON.stringify(cast.inviteCode)};

export const SOURCE_DOCUMENT: CastSource | null = ${
  cast.source
    ? `{
  id: ${JSON.stringify(cast.source.id)},
  competitionId: ${JSON.stringify(cast.source.competition_id)},
  title: ${JSON.stringify(cast.source.title)},
  filename: ${JSON.stringify(cast.source.filename)},
  status: ${JSON.stringify(cast.source.status)},
}`
    : 'null'
};

export const CAST = {
  students: STUDENTS,
  teachers: TEACHERS,
  leaderboard: LEADERBOARD,
  mainCompetition: MAIN_COMPETITION,
  inviteCode: INVITE_CODE,
  source: SOURCE_DOCUMENT,
} as const;
`;

const renderJson = (cast) =>
  `${JSON.stringify(
    {
      source: 'promo_manifest.json',
      main_competition: cast.mainCompetition,
      invite_code: cast.inviteCode,
      students: cast.students,
      teachers: cast.teachers,
      leaderboard: cast.leaderboard,
      source_document: cast.source,
    },
    null,
    2,
  )}\n`;

const main = () => {
  const manifest = readManifest();
  const cast = build(manifest);

  if (cast.students.length === 0) {
    fail('manifest contains no students; refusing to write an empty cast');
  }
  if (cast.students.some((student) => student.points <= 0)) {
    fail('every student needs a positive point total');
  }

  const tsPath = path.join(PROJECT_ROOT, 'src', 'content', 'cast.ts');
  const jsonPath = path.join(penpotDir, 'cast.json');
  const manifestRelative = path
    .relative(PROJECT_ROOT, manifestPath)
    .split(path.sep)
    .join('/');

  fs.mkdirSync(path.dirname(tsPath), { recursive: true });
  fs.mkdirSync(penpotDir, { recursive: true });
  fs.writeFileSync(tsPath, renderTs(cast, manifestRelative), 'utf8');
  fs.writeFileSync(jsonPath, renderJson(cast), 'utf8');

  const summary = {
    ok: true,
    manifest: manifestPath,
    students: cast.students.length,
    teachers: cast.teachers.length,
    leaderboard: cast.leaderboard.map(
      (student) => `${student.rank} ${student.name} ${student.points}`,
    ),
    wrote: [tsPath, jsonPath],
  };

  if (asJson) {
    process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
  } else {
    process.stdout.write('sync-cast\n');
    process.stdout.write(`  manifest: ${manifestPath}\n`);
    process.stdout.write(
      `  leaderboard: ${summary.leaderboard.join(' | ')}\n`,
    );
    process.stdout.write(`  wrote: ${tsPath}\n`);
    process.stdout.write(`  wrote: ${jsonPath}\n`);
    process.stdout.write('PASS\n');
  }
  return 0;
};

process.exit(main());
