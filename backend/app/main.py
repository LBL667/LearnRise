"""FastAPI application factory."""

import importlib
import logging
import os
import pkgutil

from fastapi import FastAPI

from app.security.redaction import install_redaction

_STARTUP_CHECKS_TRUE = frozenset({"1", "true", "yes", "on"})


def _startup_checks_enabled() -> bool:
    """Read ``STARTUP_CHECKS`` (default off; production sets ``1``)."""

    raw = os.environ.get("STARTUP_CHECKS", "0")
    return raw.strip().lower() in _STARTUP_CHECKS_TRUE


def _iter_api_routers():
    """Yield routers exposed by modules in `app.api`.

    Each API module declares a module-level `router`; the router carries its own
    full prefix (e.g. APIRouter(prefix="/api/auth")). Discovery keeps concurrent
    work from colliding on this file.
    """
    import app.api as api_pkg

    for mod_info in pkgutil.iter_modules(api_pkg.__path__):
        module = importlib.import_module(f"app.api.{mod_info.name}")
        router = getattr(module, "router", None)
        if router is not None:
            yield mod_info.name, router


def create_app() -> FastAPI:
    install_redaction(logging.getLogger())

    if _startup_checks_enabled():
        from app.startup_checks import assert_runtime_contract

        assert_runtime_contract(strict=True)

    app = FastAPI(
        title="LearnRise API",
        version="0.1.0",
        docs_url="/api/docs",
        openapi_url="/api/openapi.json",
    )

    from app.api.errors import install_error_handlers

    install_error_handlers(app)

    # --- Router registration (auto-discovery) ----------------------------
    # Add new endpoints by creating app/api/<name>.py with a module-level
    # `router`. Do NOT edit this file when adding routers.
    for name, router in _iter_api_routers():
        if name in {"health", "docs"}:
            app.include_router(router, prefix="/api")
        else:
            app.include_router(router)
    # --- End router registration -----------------------------------------

    return app


app = create_app()
