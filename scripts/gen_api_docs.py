#!/usr/bin/env python3
"""Generate ``openapi.json`` and ``docs/api/<tag>.md`` from the FastAPI app.

The script imports the application in-process (no server needs to be running),
serialises ``app.openapi()`` deterministically, and renders one Markdown file
per OpenAPI tag group.  It is the single source of truth for the generated
API documentation: every file it writes starts with a ``GENERATED`` banner and
must never be edited by hand.

Run it from the repository root (inside the backend image, which pins the
project's Python version)::

    docker compose run --rm -v "$PWD:/repo" -w /repo backend \\
        python scripts/gen_api_docs.py

The output is stable across runs: JSON keys are sorted, tag groups and
endpoints are emitted in a fixed order, and no timestamps, hostnames or
absolute paths are written.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Iterator

# Bootstraps ``import app`` from the backend package regardless of cwd.
REPO_ROOT = Path(__file__).resolve().parents[1]
BACKEND_DIR = REPO_ROOT / "backend"
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from app.main import app  # noqa: E402  (import after sys.path setup)

OPENAPI_PATH = REPO_ROOT / "openapi.json"
DOCS_DIR = REPO_ROOT / "docs" / "api"

GENERATED_BANNER = "<!-- GENERATED BY scripts/gen_api_docs.py — DO NOT EDIT -->"

REQUIRED_GROUPS: tuple[tuple[str, str], ...] = (
    ("auth", "认证"),
    ("competitions", "竞赛"),
    ("sources", "资料"),
    ("quiz", "练习"),
    ("review", "复习"),
    ("assistant", "学习助手"),
    ("dashboard", "仪表盘"),
)

EXTRA_GROUP_TITLES: dict[str, str] = {
    "agents": "智能体",
    "knowledge-points": "知识点",
    "explain": "讲解",
    "internal": "内部任务",
    "health": "健康检查",
    "notes": "结构化笔记",
}

HTTP_METHODS: tuple[str, ...] = ("get", "post", "put", "patch", "delete", "options", "head")

MAX_FIELD_DEPTH = 2

STATUS_TEXT: dict[str, str] = {
    "400": "请求不合法",
    "401": "未认证或凭证无效",
    "403": "无权限（新端点已统一为 404）",
    "404": "资源不存在或不可见",
    "409": "资源冲突",
    "413": "上传体积超限",
    "415": "不支持的内容类型",
    "422": "请求体/参数校验失败",
    "429": "请求过于频繁",
    "500": "服务器内部错误",
}


def _md_cell(value: Any) -> str:
    text = "" if value is None else str(value)
    text = text.replace("\r", " ").replace("\n", " ").replace("|", "\\|")
    return text.strip() or "—"


def _resolve_ref(schema: dict[str, Any], components: dict[str, Any]) -> dict[str, Any]:
    seen = 0
    current = schema
    while isinstance(current, dict) and "$ref" in current and seen < 8:
        ref = current["$ref"]
        if not isinstance(ref, str) or not ref.startswith("#/components/schemas/"):
            break
        name = ref.rsplit("/", 1)[-1]
        current = components.get(name, {})
        seen += 1
    return current if isinstance(current, dict) else {}


def _merge_object(schema: dict[str, Any], components: dict[str, Any]) -> dict[str, Any]:
    resolved = _resolve_ref(schema, components)
    if "allOf" not in resolved:
        return resolved
    merged: dict[str, Any] = {"type": "object", "properties": {}, "required": []}
    for part in resolved["allOf"]:
        concrete = _resolve_ref(part, components)
        merged["properties"].update(concrete.get("properties", {}))
        merged["required"].extend(concrete.get("required", []))
    merged["properties"].update(resolved.get("properties", {}))
    merged["required"].extend(resolved.get("required", []))
    merged["required"] = sorted(set(merged["required"]))
    return merged


def _type_name(schema: dict[str, Any], components: dict[str, Any]) -> str:
    if not isinstance(schema, dict) or not schema:
        return "any"
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return f"const({json.dumps(schema['const'], ensure_ascii=False)})"
    if "enum" in schema:
        values = ", ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
        return f"enum[{values}]"
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts: list[str] = []
            for sub in schema[key]:
                label = _type_name(sub, components)
                if label not in parts:
                    parts.append(label)
            return " | ".join(parts)
    if "allOf" in schema:
        return " & ".join(_type_name(sub, components) for sub in schema["allOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"array<{_type_name(schema.get('items', {}), components)}>"
    if kind is None:
        return "object" if "properties" in schema else "any"
    if schema.get("contentMediaType") or schema.get("format") == "binary":
        return f"{kind}(binary)"
    fmt = schema.get("format")
    return f"{kind}({fmt})" if fmt else str(kind)


def _default_label(schema: dict[str, Any]) -> str:
    if not isinstance(schema, dict) or "default" not in schema:
        return "—"
    return _md_cell(json.dumps(schema["default"], ensure_ascii=False))


def _iter_fields(
    schema: dict[str, Any],
    components: dict[str, Any],
    prefix: str = "",
    depth: int = 0,
) -> Iterator[tuple[str, str, bool, str]]:
    concrete = _merge_object(schema, components)
    properties = concrete.get("properties") or {}
    required = set(concrete.get("required") or [])
    for name, sub in properties.items():
        if not isinstance(sub, dict):
            sub = {}
        field = f"{prefix}.{name}" if prefix else str(name)
        yield field, _type_name(sub, components), name in required, _default_label(sub)
        if depth >= MAX_FIELD_DEPTH:
            continue
        resolved = _resolve_ref(sub, components)
        if resolved.get("type") == "object" or "properties" in resolved:
            yield from _iter_fields(resolved, components, field, depth + 1)
        elif resolved.get("type") == "array":
            item = _resolve_ref(resolved.get("items", {}), components)
            if item.get("properties"):
                yield from _iter_fields(item, components, f"{field}[]", depth + 1)


def _field_table(
    schema: dict[str, Any],
    components: dict[str, Any],
    *,
    default_column: bool,
) -> list[str]:
    header = "| 字段 | 类型 | 必填 | 默认值 |" if default_column else "| 字段 | 类型 | 必填 |"
    divider = "|---|---|---|---|" if default_column else "|---|---|---|"
    rows: list[str] = []
    for field, type_name, required, default in _iter_fields(schema, components):
        if default_column:
            rows.append(
                f"| `{_md_cell(field)}` | `{_md_cell(type_name)}` | "
                f"{'是' if required else '否'} | {default} |"
            )
        else:
            rows.append(
                f"| `{_md_cell(field)}` | `{_md_cell(type_name)}` | "
                f"{'是' if required else '否'} |"
            )
    if not rows:
        rows.append("| — | 无固定字段 | — |" + (" — |" if default_column else ""))
    return [header, divider, *rows]


def _example_value(
    schema: dict[str, Any], components: dict[str, Any], depth: int = 0
) -> Any:
    if not isinstance(schema, dict):
        return None
    if "$ref" in schema:
        return _example_value(_resolve_ref(schema, components), components, depth)
    if "const" in schema:
        return schema["const"]
    if "enum" in schema:
        return schema["enum"][0] if schema["enum"] else None
    for key in ("anyOf", "oneOf"):
        if key in schema:
            for sub in schema[key]:
                if isinstance(sub, dict) and sub.get("type") != "null":
                    return _example_value(sub, components, depth)
            return None
    kind = schema.get("type")
    if "properties" in schema or kind == "object":
        if depth >= 3:
            return {}
        concrete = _merge_object(schema, components)
        return {
            name: _example_value(sub, components, depth + 1)
            for name, sub in (concrete.get("properties") or {}).items()
        }
    if kind == "array":
        return []
    if kind == "integer":
        return 0
    if kind == "number":
        return 0
    if kind == "boolean":
        return False
    if kind == "string":
        fmt = schema.get("format")
        if fmt == "date-time":
            return "2026-01-01T00:00:00+00:00"
        if fmt == "date":
            return "2026-01-01"
        if fmt == "uuid":
            return "00000000-0000-0000-0000-000000000000"
        if fmt == "email":
            return "user@example.com"
        return "string"
    return None


def _shell_single_quote(value: str) -> str:
    return "'" + value.replace("'", "'\\''") + "'"


def _auth_line(operation: dict[str, Any]) -> str:
    if operation.get("security"):
        return (
            "需要认证：`Authorization: Bearer <JWT>`"
            "（`OAuth2PasswordBearer`，`tokenUrl=/api/auth/login`）"
        )
    return "公开端点：无需 Bearer JWT"


def _params_table(operation: dict[str, Any], components: dict[str, Any]) -> list[str]:
    params = operation.get("parameters") or []
    if not params:
        return []
    lines = ["| 名称 | 位置 | 类型 | 必填 | 默认值 |", "|---|---|---|---|---|"]
    for param in params:
        schema = param.get("schema") or {}
        lines.append(
            "| `{name}` | `{where}` | `{type}` | {required} | {default} |".format(
                name=param.get("name", ""),
                where=param.get("in", ""),
                type=_md_cell(_type_name(schema, components)),
                required="是" if param.get("required") else "否",
                default=_default_label(schema),
            )
        )
    return lines


def _request_example(operation: dict[str, Any], content_type: str) -> Any:
    body = (operation.get("requestBody") or {}).get("content") or {}
    media = body.get(content_type) or {}
    return media.get("schema") or {}


def _error_codes(operation: dict[str, Any], path: str) -> list[str]:
    responses = operation.get("responses") or {}
    codes: dict[str, str] = {}
    for code, response in responses.items():
        if str(code).startswith("2") or str(code).lower() in {"default"}:
            continue
        if str(code) == "422":
            continue
        description = (response or {}).get("description") or STATUS_TEXT.get(str(code), "")
        codes[str(code)] = description
    if operation.get("security") and "401" not in codes:
        codes["401"] = STATUS_TEXT["401"]
    if "{" in path and "404" not in codes:
        codes["404"] = "资源不存在或不可见（非成员/跨租户一律 404）"
    needs_validation = bool(operation.get("requestBody")) or bool(
        operation.get("parameters")
    )
    if needs_validation and "422" not in codes:
        codes["422"] = STATUS_TEXT["422"]
    if not codes:
        return ["未声明额外错误状态码（FastAPI 仍可能返回 500）。"]
    parts = []
    for code in sorted(codes):
        text = codes[code] or STATUS_TEXT.get(code, "")
        parts.append(f"`{code}`（{text}）" if text else f"`{code}`")
    return ["、".join(parts) + "。"]


def _curl_example(
    method: str,
    path: str,
    operation: dict[str, Any],
    components: dict[str, Any],
) -> list[str]:
    params = operation.get("parameters") or []
    query_parts: list[str] = []
    for param in params:
        if param.get("in") != "query":
            continue
        schema = param.get("schema") or {}
        if param.get("required"):
            query_parts.append(f"{param['name']}={{{param['name']}}}")
        elif "default" in schema:
            query_parts.append(f"{param['name']}={schema['default']}")
    url = "http://localhost:8000" + path
    if query_parts:
        url += "?" + "&".join(query_parts)

    lines = [f"curl -X {method.upper()} {_shell_single_quote(url)}"]
    if operation.get("security"):
        lines.append("  -H 'Authorization: Bearer $TOKEN'")

    for param in params:
        if param.get("in") == "header" and param.get("required"):
            lines.append(f"  -H '{param['name']}: {{{param['name']}}}'")

    content = (operation.get("requestBody") or {}).get("content") or {}
    if "application/json" in content:
        payload = _example_value(_request_example(operation, "application/json"), components)
        body = json.dumps(payload, ensure_ascii=False, sort_keys=True)
        lines.append("  -H 'Content-Type: application/json'")
        lines.append(f"  -d {_shell_single_quote(body)}")
    elif "multipart/form-data" in content:
        schema = _merge_object(_request_example(operation, "multipart/form-data"), components)
        for name, sub in (schema.get("properties") or {}).items():
            resolved = _resolve_ref(sub, components)
            binary = resolved.get("format") == "binary" or bool(
                resolved.get("contentMediaType")
            )
            if resolved.get("type") == "array":
                item = _resolve_ref(resolved.get("items", {}), components)
                binary = item.get("format") == "binary" or bool(item.get("contentMediaType"))
            if binary:
                lines.append(f"  -F '{name}=@/path/to/{name}'")
            else:
                value = _example_value(resolved, components)
                lines.append(f"  -F '{name}={value if value is not None else ''}'")
    return lines


def _response_schema(
    operation: dict[str, Any], components: dict[str, Any]
) -> tuple[str, dict[str, Any] | None]:
    responses = operation.get("responses") or {}
    for code in ("200", "201", "202", "204"):
        if code not in responses:
            continue
        response = responses[code] or {}
        content = response.get("content") or {}
        media = content.get("application/json") or {}
        schema = media.get("schema")
        if schema is None:
            return code, None
        resolved = _resolve_ref(schema, components)
        if resolved.get("type") == "array":
            item = _resolve_ref(resolved.get("items", {}), components)
            return code, item
        return code, resolved
    return "", None


def _render_endpoint(
    path: str,
    method: str,
    operation: dict[str, Any],
    components: dict[str, Any],
) -> list[str]:
    summary = operation.get("summary") or "—"
    description = (operation.get("description") or "").strip()
    tags = operation.get("tags") or ["default"]
    lines = [
        f"### `{method.upper()} {path}`",
        "",
        f"- **标签**: `{tags[0]}`",
        f"- **摘要**: {_md_cell(summary)}",
        f"- **鉴权**: {_auth_line(operation)}",
    ]
    if description:
        lines += ["", "**描述**", "", *[f"> {line}" if line else ">" for line in description.splitlines()]]

    params_table = _params_table(operation, components)
    if params_table:
        lines += ["", "#### 路径 / 查询 / 请求头参数", "", *params_table]

    content = (operation.get("requestBody") or {}).get("content") or {}
    if content:
        content_type = "application/json" if "application/json" in content else next(iter(content))
        schema = _request_example(operation, content_type)
        lines += [
            "",
            f"#### 请求体字段（`{content_type}`）",
            "",
            *_field_table(schema, components, default_column=True),
        ]

    status_code, response_schema = _response_schema(operation, components)
    if response_schema is None:
        lines += [
            "",
            f"#### 响应字段（{status_code or '成功响应'}）",
            "",
            "无响应体。",
        ]
    else:
        lines += [
            "",
            f"#### 响应字段（{status_code}）",
            "",
            *_field_table(response_schema, components, default_column=False),
        ]

    lines += ["", "#### 错误状态码", "", *_error_codes(operation, path)]
    curl_lines = _curl_example(method, path, operation, components)
    continued = [f"{line} \\" for line in curl_lines[:-1]] + [curl_lines[-1]]
    lines += ["", "#### curl 示例", "", "```bash", *continued, "```"]
    return lines


def _group_endpoints(spec: dict[str, Any]) -> dict[str, list[tuple[str, str, dict[str, Any]]]]:
    groups: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    paths = spec.get("paths") or {}
    for path in sorted(paths):
        operations = paths[path] or {}
        for method in HTTP_METHODS:
            operation = operations.get(method)
            if not isinstance(operation, dict):
                continue
            tags = operation.get("tags") or ["default"]
            tag = str(tags[0])
            groups.setdefault(tag, []).append((path, method, operation))
    return groups


def _render_group(tag: str, title: str, endpoints: list[tuple[str, str, dict[str, Any]]], components: dict[str, Any]) -> str:
    lines = [
        GENERATED_BANNER,
        "",
        f"# {tag} {title}",
        "",
        "> 本文件由 `scripts/gen_api_docs.py` 生成，请勿手工修改。",
        f"> 端点数量：{len(endpoints)}。",
        "",
    ]
    if not endpoints:
        lines += ["尚无端点（后续切片引入）。", ""]
        return "\n".join(lines)

    lines += ["## 端点总览", "", "| 方法 | 路径 | 摘要 |", "|---|---|---|"]
    for path, method, operation in endpoints:
        lines.append(f"| `{method.upper()}` | `{path}` | {_md_cell(operation.get('summary') or '—')} |")
    lines += ["", "## 端点详情", ""]
    for path, method, operation in endpoints:
        lines += _render_endpoint(path, method, operation, components)
        lines.append("")
    return "\n".join(lines)


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main() -> int:
    spec = app.openapi()

    spec.pop("servers", None)
    spec.pop("host", None)
    spec.pop("basePath", None)

    _write_text(
        OPENAPI_PATH,
        json.dumps(spec, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
    )

    components = (spec.get("components") or {}).get("schemas") or {}
    groups = _group_endpoints(spec)

    required_tags = [tag for tag, _ in REQUIRED_GROUPS]
    extra_tags = sorted(tag for tag in groups if tag not in required_tags)
    ordered_tags = required_tags + extra_tags

    written = 0
    for tag in ordered_tags:
        title = dict(REQUIRED_GROUPS).get(tag) or EXTRA_GROUP_TITLES.get(tag, tag)
        text = _render_group(tag, title, groups.get(tag, []), components)
        _write_text(DOCS_DIR / f"{tag}.md", text + "\n")
        written += 1

    paths = spec.get("paths") or {}
    operations = sum(
        1
        for operations_map in paths.values()
        for method in operations_map
        if method in HTTP_METHODS
    )
    print(
        f"wrote openapi.json ({len(paths)} paths, {operations} operations) "
        f"and docs/api ({written} files)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
